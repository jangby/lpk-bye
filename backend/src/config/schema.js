module.exports = [
  `CREATE TABLE IF NOT EXISTS admin_users (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'admin',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
  ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci`,
  `CREATE TABLE IF NOT EXISTS batches (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    batch_name VARCHAR(150) NOT NULL,
    program_type VARCHAR(100) NOT NULL DEFAULT 'Bahasa Jepang',
    description TEXT,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    quota INT UNSIGNED NOT NULL DEFAULT 0,
    training_fee DECIMAL(12,2) UNSIGNED NOT NULL DEFAULT 0,
    payment_instructions TEXT,
    is_active TINYINT(1) NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_batch_active (is_active),
    INDEX idx_batch_dates (start_date, end_date)
  ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci`,
  `CREATE TABLE IF NOT EXISTS form_fields (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    batch_id INT UNSIGNED NOT NULL,
    field_name VARCHAR(100) NOT NULL,
    field_label VARCHAR(150) NOT NULL,
    field_type VARCHAR(20) NOT NULL,
    options JSON,
    is_required TINYINT(1) NOT NULL DEFAULT 0,
    order_index INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_form_fields_batch_name (batch_id, field_name),
    INDEX idx_field_order (batch_id, order_index),
    CONSTRAINT fk_form_fields_batch FOREIGN KEY (batch_id) REFERENCES batches(id) ON DELETE CASCADE
  ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci`,
  `CREATE TABLE IF NOT EXISTS registrants (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    batch_id INT UNSIGNED NOT NULL,
    training_fee DECIMAL(12,2) UNSIGNED NOT NULL DEFAULT 0,
    full_name VARCHAR(150) NOT NULL,
    whatsapp VARCHAR(20) NOT NULL,
    email VARCHAR(150),
    registration_code VARCHAR(30) NOT NULL UNIQUE,
    portal_token_hash CHAR(64) NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    notes TEXT,
    participant_feedback TEXT,
    welcome_notification_status VARCHAR(20) NOT NULL DEFAULT 'pending',
    welcome_notification_error TEXT,
    status_notification_status VARCHAR(20) NOT NULL DEFAULT 'pending',
    status_notification_error TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_registrants_portal_token_hash (portal_token_hash),
    INDEX idx_registrant_status (status),
    INDEX idx_registrant_batch (batch_id),
    CONSTRAINT fk_registrants_batch FOREIGN KEY (batch_id) REFERENCES batches(id) ON DELETE RESTRICT
  ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci`,
  `CREATE TABLE IF NOT EXISTS registrant_answers (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    registrant_id INT UNSIGNED NOT NULL,
    field_id INT UNSIGNED NOT NULL,
    answer_value TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_answers_registrant_field (registrant_id, field_id),
    CONSTRAINT fk_answers_registrant FOREIGN KEY (registrant_id) REFERENCES registrants(id) ON DELETE CASCADE,
    CONSTRAINT fk_answers_field FOREIGN KEY (field_id) REFERENCES form_fields(id) ON DELETE CASCADE
  ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci`,
  `CREATE TABLE IF NOT EXISTS payments (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    registrant_id INT UNSIGNED NOT NULL,
    amount_detected DECIMAL(12,2) UNSIGNED,
    amount_approved DECIMAL(12,2) UNSIGNED,
    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    receipt_path VARCHAR(500) NOT NULL,
    sender_phone VARCHAR(30) NOT NULL,
    whatsapp_message_id VARCHAR(160) UNIQUE,
    ocr_text LONGTEXT,
    ocr_status VARCHAR(20) NOT NULL DEFAULT 'pending',
    ocr_error TEXT,
    rejection_reason TEXT,
    reviewed_by INT UNSIGNED,
    reviewed_at DATETIME,
    notification_status VARCHAR(20) NOT NULL DEFAULT 'pending',
    notification_error TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_payments_registrant (registrant_id, status),
    INDEX idx_payments_status_created (status, created_at),
    CONSTRAINT fk_payments_registrant FOREIGN KEY (registrant_id) REFERENCES registrants(id) ON DELETE CASCADE,
    CONSTRAINT fk_payments_reviewer FOREIGN KEY (reviewed_by) REFERENCES admin_users(id) ON DELETE SET NULL
  ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci`
];
